using System.Text;
using Awaiten.SourceGenerators.Entities;
using Microsoft.CodeAnalysis.CSharp;

namespace Awaiten.SourceGenerators;

/// <summary>
///     Emits the generated partial of a <c>[Module]</c> that self-compiles its <c>[Scan]</c>: the module class is
///     re-opened as <c>partial</c>, carrying one <c>[GeneratedScanRegistration]</c> per match and one
///     <c>public static</c> factory method, in the nested <c>Internals</c> class that holds every generated member, that
///     constructs the match and returns its accessible exposure interface.
///     The factory body <c>new</c>s the (possibly <c>internal</c>) implementation - legal because this code compiles
///     in the module's own assembly - while the consumer only ever names the interface and calls the factory. A
///     self-compiled registration gets a factory of the same shape, without an attribute: the consumer finds it by name.
/// </summary>
internal static partial class Sources
{
	public static string EmitModule(ModuleScanModel model)
	{
		StringBuilder builder = new();
		builder.AppendLine("// <auto-generated/>");
		builder.AppendLine("#nullable enable");
		builder.AppendLine();

		int depth = 0;
		bool hasNamespace = !string.IsNullOrEmpty(model.Namespace);
		if (hasNamespace)
		{
			builder.Append("namespace ").AppendLine(model.Namespace);
			builder.AppendLine("{");
			depth++;
		}

		foreach (TypeDeclaration containing in model.ContainingTypes.AsArray())
		{
			Indent(builder, depth).Append("partial ").Append(containing.Keyword).Append(' ').AppendLine(containing.Name);
			Indent(builder, depth).AppendLine("{");
			depth++;
		}

		// The expansion marker: proof the module's [Scan] passed through the generator, emitted even when the
		// scan matched nothing, so a consuming container can tell "matched nothing" from "never expanded" and
		// report AWT154 only for the latter (a module assembly built without the Awaiten generator).
		if (model.DeclaresScan)
		{
			Indent(builder, depth).AppendLine("[global::Awaiten.GeneratedScanExpansionAttribute]");
		}

		// One [GeneratedScanRegistration] per generated factory, applied to the re-opened partial module. The
		// consuming container reads these like a container [Scan]'s matches (collection-eligible and overridable).
		foreach (ModuleFactory factory in model.Factories.AsArray())
		{
			if (factory.Skip is { } skip)
			{
				foreach (string service in skip.Services.AsArray())
				{
					Indent(builder, depth).Append('[').Append(RegistrationAttribute(factory with { FactoryName = skip.ImplementationMetadataName, ServiceType = service, })).AppendLine("]");
				}
			}
			else
			{
				Indent(builder, depth).Append('[').Append(RegistrationAttribute(factory)).AppendLine("]");
			}
		}

		Indent(builder, depth).Append("static partial class ").AppendLine(model.TypeName);
		Indent(builder, depth).AppendLine("{");

		bool hasMembers = model.Factories.Count > 0 || model.Registrations.Count > 0 || model.Wrappers.Count > 0 || model.Skipped.Count > 0
		                  || model.Handles.Count > 0;
		if (hasMembers)
		{
			OpenInternals(builder, depth + 1, "public",
				"Generated from the module's registrations and scans: the factories, wrappers and skip records a consuming",
				"container calls or reads. Not intended to be used directly.");
		}

		bool first = true;
		foreach (ModuleFactory factory in model.Factories.AsArray())
		{
			if (!first)
			{
				builder.AppendLine();
			}

			first = false;
			if (factory.Skip is { } skip)
			{
				EmitSkipReason(builder, depth + 2, skip.MarkerName, skip.Reason,
					"Generated from a module [Scan]: why no factory constructs this match. An assembly granted InternalsVisibleTo",
					"constructs it itself; a consuming container that cannot reports this reason.");
			}
			else
			{
				EmitModuleFactory(builder, depth + 2, factory);
			}

			// The lifecycle-hook wrappers, emitted beside the factory: public so a cross-assembly consumer can run
			// them, but bodied inside the module so they may cast to and call its internal implementation and hook.
			if (factory.OnActivated is { SkipReason: null, } activation)
			{
				builder.AppendLine();
				EmitModuleHook(builder, depth + 2, factory.ServiceType, activation, release: false, ScanOrigin);
			}

			if (factory.OnRelease is { SkipReason: null, } release)
			{
				builder.AppendLine();
				EmitModuleHook(builder, depth + 2, factory.ServiceType, release, release: true, ScanOrigin);
			}
		}

		foreach (RegistrationFactory registration in model.Registrations.AsArray())
		{
			if (!first)
			{
				builder.AppendLine();
			}

			first = false;
			EmitRegistrationFactory(builder, depth + 2, registration);
			foreach (RegistrationHook hook in registration.Hooks.AsArray())
			{
				builder.AppendLine();
				EmitModuleHook(builder, depth + 2, registration.ReturnType, hook.Hook, hook.Release, RegistrationOrigin, registration.Handle is not null);
			}
		}

		foreach (HiddenHandle handle in model.Handles.AsArray())
		{
			builder.AppendLine();
			EmitHiddenHandle(builder, depth + 2, handle);
		}

		foreach (HiddenAlias alias in model.Aliases.AsArray())
		{
			builder.AppendLine();
			AppendXmlSummary(builder, depth + 2,
				"Generated from a module registration: serves another service of an implementation the module registers under an",
				"internal service, from the handle that owns its instance, so every service shares the one instance.");
			Indent(builder, depth + 2).Append("public static ").Append(alias.ReturnType).Append(' ').Append(alias.Name).Append('(')
				.Append(alias.Attributes).Append(alias.HandleType).Append(" @awaiten__handle) => ").Append(alias.Body).AppendLine(";");
		}

		foreach (HiddenInitializer initializer in model.Initializers.AsArray())
		{
			builder.AppendLine();
			AppendXmlSummary(builder, depth + 2,
				"Generated from a module [AsyncInitializer]: runs the convention on the instance a handle holds, so a consuming",
				"container initializes a service the module registers under an internal service type.");
			FactoryParameter[] parameters = initializer.Parameters.AsArray();
			Indent(builder, depth + 2).Append("public static ").Append(initializer.ReturnType).Append(' ').Append(initializer.Name).Append('(')
				.Append(initializer.HandleType).Append(" @awaiten__instance").Append(string.Concat(parameters.Select(parameter => $", {MirroredParameter(parameter)}")))
				.Append(") => ((").Append(initializer.ConventionType).Append(")@awaiten__instance.Value).").Append(initializer.Method).Append('(')
				.Append(string.Join(", ", parameters.Select(parameter => parameter.ArgumentExpression))).AppendLine(");");
		}

		foreach (MemberWrapper wrapper in model.Wrappers.AsArray())
		{
			if (!first)
			{
				builder.AppendLine();
			}

			first = false;
			EmitMemberWrapper(builder, depth + 2, wrapper, "public",
				"Generated from a module registration: forwards to the module's own member, which a consuming container in",
				"another assembly cannot call.");
		}

		foreach (SkippedRegistration skipped in model.Skipped.AsArray())
		{
			if (!first)
			{
				builder.AppendLine();
			}

			first = false;
			if (skipped.Hook)
			{
				EmitSkipReason(builder, depth + 2, skipped.MarkerName, skipped.Reason,
					"Generated from a module registration: why no wrapper runs this lifecycle hook. An assembly granted",
					"InternalsVisibleTo calls the hook itself; a consuming container that cannot reports this reason.");
			}
			else
			{
				EmitSkipReason(builder, depth + 2, skipped.MarkerName, skipped.Reason,
					"Generated from a module registration: why no factory constructs this implementation. An assembly granted",
					"InternalsVisibleTo constructs it itself; a consuming container that cannot reports this reason.");
			}
		}

		if (hasMembers)
		{
			Indent(builder, depth + 1).AppendLine("}");
		}

		Indent(builder, depth).AppendLine("}");

		for (int i = 0; i < model.ContainingTypes.Count; i++)
		{
			depth--;
			Indent(builder, depth).AppendLine("}");
		}

		if (hasNamespace)
		{
			builder.AppendLine("}");
		}

		return builder.ToString();
	}

	/// <summary>
	///     Emits the internal type that records a module the generator left to the assemblies granted
	///     <c>InternalsVisibleTo</c> because it is not partial. A consumer finds it in the module's namespace, since
	///     metadata carries the internal types of another assembly but not its internal members.
	/// </summary>
	public static string EmitModuleNotPartialMarker(ModuleScanModel model)
	{
		StringBuilder builder = new();
		builder.AppendLine("// <auto-generated/>");
		builder.AppendLine("#nullable enable");
		builder.AppendLine();

		int depth = 0;
		if (!string.IsNullOrEmpty(model.Namespace))
		{
			builder.Append("namespace ").AppendLine(model.Namespace);
			builder.AppendLine("{");
			depth++;
		}

		AppendXmlSummary(builder, depth,
			$"Generated for the module {model.TypeName}, which is not partial and so carries no factory: an assembly granted",
			"InternalsVisibleTo constructs its implementations itself, and a consuming container that cannot reports why.");
		Indent(builder, depth).Append("internal static class ").AppendLine(model.NotPartialMarker);
		Indent(builder, depth).AppendLine("{");
		Indent(builder, depth).AppendLine("}");

		if (depth > 0)
		{
			builder.AppendLine("}");
		}

		return builder.ToString();
	}

	/// <summary>
	///     The registration attribute for one factory: the service is the accessible exposure interface the
	///     generated factory produces, and the lifetime is the one the scan declared. A consuming container reads
	///     <c>[GeneratedScanRegistration]</c> like a container <c>[Scan]</c>'s match - collection-eligible so
	///     several matches under one interface resolve as an <c>IEnumerable</c>, and overridable by an explicit
	///     registration - so a self-compiled scan behaves as close to a container scan as the assembly boundary allows.
	/// </summary>
	private static string RegistrationAttribute(ModuleFactory factory)
	{
		string skip = factory.SkipUnconstructable ? ", SkipUnconstructable = true" : string.Empty;

		// The hook wrapper names travel on the registration so a consumer runs them through the ordinary hook
		// pipeline, exactly like OnActivated/OnRelease on a container [Scan]. Every name is relative to the module, so
		// a generated member carries its Internals class and a skipped one names the module's own member.
		string onActivated = factory.OnActivated is { } activation ? $", OnActivated = \"{RelativeName(activation.WrapperName, activation.SkipReason is null)}\"" : string.Empty;
		string onRelease = factory.OnRelease is { } release ? $", OnRelease = \"{RelativeName(release.WrapperName, release.SkipReason is null)}\"" : string.Empty;

		// What the consumer cannot read off the match it never sees: async initialization and disposal.
		string asyncInitializable = factory.Traits.AsyncInitializers.Count > 0
			? $", AsyncInitializers = new global::System.Type[] {{ {string.Join(", ", factory.Traits.AsyncInitializers.Select(type => $"typeof({type})"))} }}"
			  + $", AsyncInitializerMethods = new string[] {{ {string.Join(", ", factory.Traits.AsyncInitializerMethods.Select(method => $"\"{method}\""))} }}"
			: string.Empty;
		string disposable = factory.Traits.Disposable ? ", Disposable = true" : string.Empty;
		string asyncDisposable = factory.Traits.AsyncDisposable ? ", AsyncDisposable = true" : string.Empty;
		string implementation = factory is { Skip: null, ImplementationMetadataName: { } name, } ? $", Implementation = \"{name}\"" : string.Empty;
		return $"global::Awaiten.GeneratedScanRegistrationAttribute<{factory.ServiceType}>(\"{RelativeName(factory.FactoryName, factory.Skip is null)}\", Lifetime = global::Awaiten.Lifetime.{factory.Lifetime}{skip}{onActivated}{onRelease}{asyncInitializable}{disposable}{asyncDisposable}{implementation})";
	}

	/// <summary>
	///     The name of a member relative to the module that owns it: a <paramref name="generated" /> one sits in the
	///     generated Internals class, any other is the module's own.
	/// </summary>
	private static string RelativeName(string name, bool generated)
		=> generated ? $"{AwaitenGenerator.InternalsClass}.{name}" : name;

	/// <summary>
	///     Opens the nested class that holds every member the generator adds to a module or container, hidden from
	///     IntelliSense, so the generated plumbing stays apart from the user's own members.
	/// </summary>
	private static void OpenInternals(StringBuilder builder, int depth, string accessibility, params string[] summary)
	{
		AppendXmlSummary(builder, depth, summary);
		Indent(builder, depth).AppendLine("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
		Indent(builder, depth).Append(accessibility).Append(" static class ").AppendLine(AwaitenGenerator.InternalsClass);
		Indent(builder, depth).AppendLine("{");
	}

	/// <summary>
	///     Emits the handle of a service the module registers under an internal type (see <see cref="HiddenHandle" />): a
	///     public class another assembly can name but neither create nor unwrap, plus a sealed variant for each disposal
	///     shape an implementation of the service needs, which forwards disposal to the instance.
	/// </summary>
	private static void EmitHiddenHandle(StringBuilder builder, int depth, HiddenHandle handle)
	{
		AppendXmlSummary(builder, depth,
			"Generated from a module registration: holds an instance of a service the module registers under an internal",
			"type, so a consuming container in another assembly depends on it without naming the service. Not intended to be used directly.");
		Indent(builder, depth).AppendLine("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
		Indent(builder, depth).Append("public class ").AppendLine(handle.Name);
		Indent(builder, depth).AppendLine("{");
		Indent(builder, depth + 1).Append("internal ").Append(handle.Name).Append('(').Append(handle.ValueType).AppendLine(" value) => Value = value;");
		builder.AppendLine();
		Indent(builder, depth + 1).Append("internal ").Append(handle.ValueType).AppendLine(" Value { get; }");
		const string dispose = "void global::System.IDisposable.Dispose() => ((global::System.IDisposable)Value).Dispose();";
		const string disposeAsync = "global::System.Threading.Tasks.ValueTask global::System.IAsyncDisposable.DisposeAsync() => ((global::System.IAsyncDisposable)Value).DisposeAsync();";
		if (handle.Disposable)
		{
			EmitHandleVariant(builder, depth + 1, handle, "Disposable", "global::System.IDisposable", dispose);
		}

		if (handle.AsyncDisposable)
		{
			EmitHandleVariant(builder, depth + 1, handle, "AsyncDisposable", "global::System.IAsyncDisposable", disposeAsync);
		}

		if (handle.BothDisposable)
		{
			EmitHandleVariant(builder, depth + 1, handle, "BothDisposable", "global::System.IDisposable, global::System.IAsyncDisposable", dispose, disposeAsync);
		}

		Indent(builder, depth).AppendLine("}");
	}

	private static void EmitHandleVariant(StringBuilder builder, int depth, HiddenHandle handle, string name, string interfaces, params string[] members)
	{
		builder.AppendLine();
		Indent(builder, depth).Append("internal sealed class ").Append(name).Append(" : ").Append(handle.Name).Append(", ").AppendLine(interfaces);
		Indent(builder, depth).AppendLine("{");
		Indent(builder, depth + 1).Append("internal ").Append(name).Append('(').Append(handle.ValueType).AppendLine(" value) : base(value) { }");
		foreach (string member in members)
		{
			builder.AppendLine();
			Indent(builder, depth + 1).AppendLine(member);
		}

		Indent(builder, depth).AppendLine("}");
	}

	private const string ScanOrigin = "a module [Scan]";

	private const string RegistrationOrigin = "a module registration";

	/// <summary>
	///     Emits the factory of a self-compiled module registration: it constructs the implementation, which only
	///     the module's own assembly (or, for a type nested privately in it, only the module) may, and returns it as an
	///     accessible type a consumer names in its stead.
	/// </summary>
	private static void EmitRegistrationFactory(StringBuilder builder, int depth, RegistrationFactory factory)
		=> EmitRegistrationFactory(builder, depth, factory, "public",
			"Generated from a module registration: constructs an implementation a consuming container cannot construct and",
			"returns it as an accessible type, so a consuming container resolves it without naming the implementation.");

	/// <summary>
	///     Emits a generated factory with the given accessibility and summary: a static method that constructs the
	///     implementation, which only its owner may, and returns it as the accessible type a consumer names in its stead.
	/// </summary>
	private static void EmitRegistrationFactory(StringBuilder builder, int depth, RegistrationFactory factory, string accessibility, params string[] summary)
	{
		AppendXmlSummary(builder, depth, summary);

		FactoryParameter[] parameters = factory.Parameters.AsArray();
		string[] members = factory.Members.AsArray();
		string signature = string.Join(", ", parameters.Select(MirroredParameter));
		string arguments = string.Join(", ", parameters.Take(parameters.Length - members.Length).Select(parameter => parameter.ArgumentExpression));

		Indent(builder, depth)
			.Append(accessibility).Append(" static ").Append(factory.ReturnType).Append(' ').Append(factory.FactoryName)
			.Append('(').Append(signature).Append(") => ");
		if (factory.Handle is not null)
		{
			builder.Append("new ").Append(factory.Handle).Append('(');
		}

		builder.Append("new ").Append(factory.ImplementationType).Append('(').Append(arguments).Append(')');
		if (members.Length > 0)
		{
			FactoryParameter[] memberParameters = parameters.Skip(parameters.Length - members.Length).ToArray();
			builder.Append(" { ").Append(string.Join(", ", members.Select((member, index) => $"{member} = {memberParameters[index].ArgumentExpression}"))).Append(" }");
		}

		builder.AppendLine(factory.Handle is null ? ";" : ");");
	}

	/// <summary>
	///     Emits the public constant that records why the module generates no code a consumer would otherwise call.
	///     A consumer reads it from metadata, which carries no internal member of another assembly.
	/// </summary>
	private static void EmitSkipReason(StringBuilder builder, int depth, string name, string reason, params string[] summary)
	{
		AppendXmlSummary(builder, depth, summary);
		Indent(builder, depth)
			.Append("public const string ").Append(name).Append(" = ")
			.Append(SymbolDisplay.FormatLiteral(reason, quote: true)).AppendLine(";");
	}

	/// <summary>
	///     Emits a wrapper with the given accessibility that forwards to a member of its owner a consuming container
	///     cannot call: a method passing its parameters on, or a property returning the member.
	/// </summary>
	private static void EmitMemberWrapper(StringBuilder builder, int depth, MemberWrapper wrapper, string accessibility, params string[] summary)
	{
		AppendXmlSummary(builder, depth, summary);
		Indent(builder, depth).Append(accessibility).Append(" static ").Append(wrapper.ReturnType).Append(' ').Append(wrapper.Name);
		if (wrapper.IsProperty)
		{
			builder.Append(" => ").Append(wrapper.Target).AppendLine(";");
			return;
		}

		FactoryParameter[] parameters = wrapper.Parameters.AsArray();
		builder.Append('(').Append(string.Join(", ", parameters.Select(MirroredParameter))).Append(") => ").Append(wrapper.Target)
			.Append('(').Append(string.Join(", ", parameters.Select(parameter => $"@{parameter.Name}"))).AppendLine(");");
	}

	/// <summary>A mirrored parameter as it is declared on a generated factory or wrapper, with its attributes.</summary>
	private static string MirroredParameter(FactoryParameter parameter)
		=> $"{parameter.Attributes}{parameter.Type} @{parameter.Name}";

	private static void EmitModuleFactory(StringBuilder builder, int depth, ModuleFactory factory)
	{
		AppendXmlSummary(builder, depth,
			"Generated from a module [Scan]: constructs the scanned implementation and exposes it through its",
			"accessible interface, so a consuming container resolves it without naming the implementation.");

		// Parameter names are emitted verbatim-prefixed: a scanned constructor may legally name a parameter with a
		// reserved keyword ('@event'), whose symbol name carries no '@', and the prefix is harmless otherwise.
		FactoryParameter[] parameters = factory.Parameters.AsArray();
		string signature = string.Join(", ", parameters.Select(MirroredParameter));
		string arguments = string.Join(", ", parameters.Select(parameter => parameter.ArgumentExpression));

		Indent(builder, depth)
			.Append("public static ").Append(factory.ServiceType).Append(' ').Append(factory.FactoryName)
			.Append('(').Append(signature).Append(") => new ").Append(factory.ImplementationType)
			.Append('(').Append(arguments).AppendLine(");");
	}

	/// <summary>
	///     Emits one lifecycle-hook wrapper: a <c>public static</c> method returning what the hook returns (so an
	///     asynchronous hook's task reaches the consumer), taking the accessible exposure interface as its first parameter, casting it to the hook's own instance parameter type (the internal
	///     implementation, a base type it accepts, or the closed marker form of a generic hook) and forwarding it -
	///     plus the graph-resolved parameters after it - to the module's own (possibly <c>internal</c>) hook. The
	///     cast and the call compile because the wrapper body sits in the module's own assembly, while the
	///     <c>public</c> signature is all a consumer needs to run it.
	/// </summary>
	private static void EmitModuleHook(StringBuilder builder, int depth, string instanceType, ModuleHook hook, bool release, string origin, bool fromHandle = false)
		=> EmitHookWrapper(builder, depth, "public", instanceType, hook, fromHandle,
			$"Generated from {origin}: the {(release ? "OnRelease" : "OnActivated")} lifecycle wrapper, casting the exposure",
			"interface to the hook's own instance parameter type and forwarding to the module's own hook, so a consumer runs it without naming the internal hook.");

	/// <summary>
	///     Emits a lifecycle-hook wrapper with the given accessibility and summary (see <see cref="EmitModuleHook" />).
	/// </summary>
	private static void EmitHookWrapper(StringBuilder builder, int depth, string accessibility, string instanceType, ModuleHook hook, bool fromHandle, params string[] summary)
	{
		AppendXmlSummary(builder, depth, summary);

		FactoryParameter[] parameters = hook.Parameters.AsArray();
		string signature = string.Concat(parameters.Select(parameter => $", {MirroredParameter(parameter)}"));
		string arguments = string.Concat(parameters.Select(parameter => $", {parameter.ArgumentExpression}"));

		// The synthetic instance parameter starts from an awaiten__ prefix so it is very unlikely to collide with a
		// mirrored user hook parameter (a plain name like "instance" would be a duplicate-parameter error in the
		// wrapper), and is suffixed away from any mirrored name that does collide - the prefix is a convention, not
		// enforced on the user's hook.
		StringBuilder instanceName = new("awaiten__instance");
		string instance = instanceName.ToString();
		while (parameters.Any(parameter => parameter.Name == instance))
		{
			instance = instanceName.Append('_').ToString();
		}

		Indent(builder, depth)
			.Append(accessibility).Append(" static ").Append(hook.ReturnType).Append(' ').Append(hook.WrapperName)
			.Append('(').Append(instanceType).Append(" @").Append(instance).Append(signature).Append(") => ")
			.Append(hook.Target).Append("((").Append(hook.InstanceCast).Append(")@").Append(instance).Append(fromHandle ? ".Value" : string.Empty).Append(arguments).AppendLine(");");
	}
}
